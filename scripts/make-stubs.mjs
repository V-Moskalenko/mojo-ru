let created = 0;
let skipped = 0;

for (const [path, title, order, description, plan] of PAGES) {
  const file = join(ROOT, `${path}.mdx`);
  if (existsSync(file)) {
    skipped++;
    continue;
  }
  mkdirSync(dirname(file), { recursive: true });

  const body = `---
title: "${title.replaceAll(String.raw`"`, String.raw`\"`)}"
description: "${description.replace(/"/g, String.raw`\"`)}"
sidebar:
  order: ${order}
  badge:
    text: в работе
    variant: note
wip: true
---

import { Aside } from '@astrojs/starlight/components';

<Aside type="note" title="Глава пишется">
  Эта страница — часть плана курса. Текст ещё не написан, но структура
  зафиксирована: так видно, куда движется проект, и можно предложить
  свою тему или правку заранее.
</Aside>

## Что будет в этой главе

${plan.map((p) => `- ${p}`).join('\n')}

## Хотите ускорить

Курс развивается открыто. Если эта тема нужна вам прямо сейчас —
напишите об этом в репозитории проекта, главы пишутся в порядке
спроса, а не строго по номерам.
`;

  writeFileSync(file, body, 'utf-8');
  created++;
}

console.log(`Создано страниц: ${created}, пропущено (уже есть): ${skipped}`);
